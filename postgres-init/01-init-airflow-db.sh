#!/bin/bash
set -e

# Conecta no banco principal e cria o ecossistema isolado do airflow
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE USER $POSTGRES_USER_AIRFLOW WITH PASSWORD '$POSTGRES_PASSWORD_AIRFLOW';
    CREATE DATABASE $POSTGRES_DB_AIRFLOW;
    GRANT ALL PRIVILEGES ON DATABASE $POSTGRES_DB_AIRFLOW TO $POSTGRES_USER_AIRFLOW;
    
    \c $POSTGRES_DB_AIRFLOW
    GRANT ALL ON SCHEMA public TO $POSTGRES_USER_AIRFLOW;
EOSQL